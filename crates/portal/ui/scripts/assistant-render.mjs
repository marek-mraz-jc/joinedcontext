// Writes src/generated/assistantRender.js, the assistant's one render core for the Portal chat
// (T-7790): the field labels (jc-core data/field-order.json) as JC_FIELDS, the widget's render.js
// as it is, and an ES export. The public widget loads the same render.js after the same labels,
// so both shells read an answer with one Markdown subset, one link allowlist and one reducer.
//
//   node scripts/assistant-render.mjs          writes the file
//   node scripts/assistant-render.mjs --check  fails when the committed file is not what it would write
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const platform = join(here, "../../../../vendor/joinedcontext-platform/crates");
const out = join(here, "../src/generated/assistantRender.js");

// render.js's CommonJS export for `node --test`; the module exports it as ES instead.
const COMMONJS = /\nif \(typeof module !== "undefined"\) module\.exports = JCRender;\s*$/;

/** The module's text from the labels' JSON and render.js's source. */
export function generate(fields, render) {
  if (!COMMONJS.test(render)) throw new Error("render.js no longer ends on its CommonJS export: update scripts/assistant-render.mjs");
  return [
    "// Generated by scripts/assistant-render.mjs from vendor/joinedcontext-platform/crates/jc-core/data/field-order.json",
    "// and crates/assistant/widget/render.js: do not edit by hand. CI regenerates it and fails on any difference.",
    "/* eslint-disable */",
    `const JC_FIELDS = ${JSON.stringify(JSON.parse(fields))};`,
    render.replace(COMMONJS, ""),
    "export default JCRender;",
    "",
  ].join("\n");
}

const text = generate(
  readFileSync(join(platform, "jc-core/data/field-order.json"), "utf8"),
  readFileSync(join(platform, "assistant/widget/render.js"), "utf8"),
);
if (process.argv.includes("--check")) {
  let committed = "";
  try {
    committed = readFileSync(out, "utf8");
  } catch {
    // A missing file is stale too.
  }
  if (committed !== text) {
    console.error("src/generated/assistantRender.js is stale: run `node scripts/assistant-render.mjs` in crates/portal/ui and commit it");
    process.exit(1);
  }
} else {
  writeFileSync(out, text);
}
