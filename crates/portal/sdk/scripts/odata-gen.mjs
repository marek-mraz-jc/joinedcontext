// Generates src/sdk/odata/generated.ts from the org-admin's CSDL JSON (odata/org-admin.metadata.json,
// written by the Portal's test sdk_metadata_snapshot_is_the_org_admins_metadata, T-6816).
//
//   node scripts/odata-gen.mjs          writes the file
//   node scripts/odata-gen.mjs --check  fails when the committed file is not what it would write
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const NAMESPACE = "JoinedContext.Portal";

const EDM = {
  "Edm.String": "string",
  "Edm.Boolean": "boolean",
  "Edm.Int16": "number",
  "Edm.Int32": "number",
  "Edm.Int64": "number",
  "Edm.Double": "number",
  "Edm.Decimal": "number",
  "Edm.DateTimeOffset": "string",
  "Edm.Date": "string",
  "Edm.Guid": "string",
  "Edm.Untyped": "unknown",
};

const local = (type) => type.replace(`${NAMESPACE}.`, "");
const tsType = (type = "Edm.String") => EDM[type] ?? local(type);
const sorted = (o) => Object.keys(o).sort();
const quoted = (name) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name));

/** The TypeScript module of `csdl`, a CSDL JSON document of the Portal's Organization service. */
export function generate(csdl) {
  const schema = csdl[NAMESPACE];
  if (!schema) throw new Error(`no schema ${NAMESPACE} in the CSDL`);
  const containerName = local(csdl.$EntityContainer ?? "");
  const container = schema[containerName] ?? {};
  const out = [
    "// Generated by scripts/odata-gen.mjs from odata/org-admin.metadata.json: do not edit by hand.",
    "// The Portal's OData service per Organization (ADR-N-070, API/13 §2a); CI regenerates it and",
    "// fails on any difference (T-6816).",
    "",
  ];
  const types = sorted(schema).filter((n) => schema[n]?.$Kind === "EntityType");
  for (const name of types) {
    const type = schema[name];
    out.push(`export interface ${name} {`);
    for (const member of sorted(type).filter((m) => !m.startsWith("$"))) {
      const p = type[member];
      if (p.$Kind === "NavigationProperty") continue;
      const optional = p.$Nullable ? "?" : "";
      const nullable = p.$Nullable ? " | null" : "";
      const element = tsType(p.$Type);
      const ts = p.$Collection ? `${element}[]` : element;
      out.push(`  ${quoted(member)}${optional}: ${ts}${nullable};`);
    }
    out.push(`  "@odata.etag"?: string;`, "}", "");
  }
  const sets = sorted(container).filter((n) => !n.startsWith("$") && container[n].$Collection);
  const singletons = sorted(container).filter((n) => !n.startsWith("$") && !container[n].$Collection);
  out.push("/** Each entity set and the type of its rows. */", "export interface EntitySets {");
  for (const set of sets) out.push(`  ${quoted(set)}: ${local(container[set].$Type)};`);
  out.push("}", "", "/** Each singleton and its type. */", "export interface Singletons {");
  for (const one of singletons) out.push(`  ${quoted(one)}: ${local(container[one].$Type)};`);
  out.push("}", "", "/** Each entity set's key members, in key order. */");
  out.push("export const ENTITY_KEYS: { readonly [S in keyof EntitySets]: readonly string[] } = {");
  for (const set of sets) {
    const key = schema[local(container[set].$Type)]?.$Key ?? [];
    out.push(`  ${quoted(set)}: ${JSON.stringify(key)},`);
  }
  out.push("};", "");
  for (const kind of ["Function", "Action"]) {
    const names = sorted(schema).filter(
      (n) => Array.isArray(schema[n]) && schema[n].some((o) => o.$Kind === kind),
    );
    out.push(`/** Each bound ${kind.toLowerCase()} and its parameters. */`, `export interface ${kind}s {`);
    for (const name of names) {
      // Overloads differ only by their binding: their parameters are one set.
      const params = new Map();
      for (const overload of schema[name]) {
        for (const p of (overload.$Parameter ?? []).slice(1)) params.set(p.$Name, p);
      }
      const members = [...params.values()].map(
        (p) => `${quoted(p.$Name)}${p.$Nullable === false ? "" : "?"}: ${tsType(p.$Type)}`,
      );
      const shape = members.length ? `{ ${members.join("; ")} }` : "Record<string, never>";
      out.push(`  ${quoted(name)}: ${shape};`);
    }
    out.push("}", "", `/** The entity types each ${kind.toLowerCase()} is bound to. */`);
    out.push(`export const ${kind.toUpperCase()}_BINDINGS: { readonly [N in keyof ${kind}s]: readonly string[] } = {`);
    for (const name of names) {
      const bindings = schema[name].map((o) => local(o.$Parameter?.[0]?.$Type ?? ""));
      out.push(`  ${quoted(name)}: ${JSON.stringify([...new Set(bindings)].sort())},`);
    }
    out.push("};", "");
  }
  return out.join("\n");
}

const here = dirname(fileURLToPath(import.meta.url));
export const SNAPSHOT = join(here, "..", "odata", "org-admin.metadata.json");
export const TARGET = join(here, "..", "src", "sdk", "odata", "generated.ts");

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = generate(JSON.parse(readFileSync(SNAPSHOT, "utf8")));
  if (process.argv.includes("--check")) {
    let committed = "";
    try {
      committed = readFileSync(TARGET, "utf8");
    } catch {
      committed = "";
    }
    if (committed !== text) {
      console.error(
        "src/sdk/odata/generated.ts is not what odata/org-admin.metadata.json generates: " +
          "run node scripts/odata-gen.mjs and commit the result, never edit it by hand",
      );
      process.exit(1);
    }
    console.log("src/sdk/odata/generated.ts matches the $metadata snapshot");
  } else {
    writeFileSync(TARGET, text);
  }
}
