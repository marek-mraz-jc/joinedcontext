#!/bin/sh
# End-to-end parity of ekiben with Bento 1.22.0 over every deployment seed pipeline (T-6624).
#
#   scripts/e2e-parity.sh [--record] [--only project/name ...]
#
# Renders each seed pipeline as the Portal hands it to the runner (tools/portal-render), runs it
# one-shot in .bento/bento and in `ekiben run` against the replay stub (scripts/e2e/stub.py) and
# writes the verdict per pipeline to docs/parity/e2e-pipelines.md. Answers come from the fixture
# store (.parity/fixtures, or $EKIBEN_PARITY_FIXTURES); --record fetches a missing answer from the
# real source once and stores it. Exit 0 only when every runnable pipeline is identical.
#
# Env: DEPLOYMENT_DIR (joinedcontext-deployment clone, default ../joinedcontext-deployment),
#      PARITY_OUT (work dir, default .parity/out), JOBS (default: number of cores).
set -eu
cd "$(dirname "$0")/.."
DEPLOYMENT_DIR=${DEPLOYMENT_DIR:-../joinedcontext-deployment}
OUT=${PARITY_OUT:-.parity/out}
TARGET=${CARGO_TARGET_DIR:-target}
sh scripts/reference-bento.sh >/dev/null
cargo build --release --locked -q -p ekiben-server
cargo build --release --locked -q --manifest-path tools/portal-render/Cargo.toml --target-dir "$TARGET"
mkdir -p "$OUT"
"$TARGET/release/portal-render" "$DEPLOYMENT_DIR/components/context-gateway/seed" > "$OUT/rendered.jsonl"
echo "deployment $(git -C "$DEPLOYMENT_DIR" rev-parse --short HEAD), $(wc -l < "$OUT/rendered.jsonl") pipelines rendered"
exec python3 scripts/e2e/parity.py run --rendered "$OUT/rendered.jsonl" --out "$OUT" \
  --resources "$DEPLOYMENT_DIR/components/pipeline-runner/streams/resources.yaml" \
  --fixtures "${EKIBEN_PARITY_FIXTURES:-.parity/fixtures}" --jobs "${JOBS:-$(nproc)}" \
  --ekiben "$TARGET/release/ekiben" --table docs/parity/e2e-pipelines.md \
  --source "Generated by scripts/e2e-parity.sh from joinedcontext-deployment $(git -C "$DEPLOYMENT_DIR" rev-parse --short HEAD) seeds, rendered as joinedcontext-portal d7f91eb28 renders them (tools/portal-render), $(date -u +%Y-%m-%d)." "$@"
