#!/usr/bin/env python3
"""Write crates/ekiben-bloblang/src/required_params.rs: the first required parameter of every Bento 1.22.0 Bloblang
method and function, found by calling each with no arguments through `.bento/bento blobl` and reading its
`missing parameter: <name>` parse error. Usage: python3 scripts/corpus/required_params.py"""
import json
import os
import re
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BENTO = os.path.join(ROOT, ".bento", "bento")
names = json.loads(subprocess.run([BENTO, "list", "--format", "json"], capture_output=True, text=True).stdout)


def first_required(expr):
    p = subprocess.run([BENTO, "blobl", f"root = {expr}"], input="{}\n", capture_output=True, text=True, errors="replace", timeout=20)
    m = re.search(r"^failed to parse mapping: line 1 char \d+: missing parameter: (\w+)$", p.stderr, re.M)
    return m.group(1) if m else None


out = ["// Generated by scripts/corpus/required_params.py from Bento 1.22.0; do not edit.",
       "//! First required parameter of each Bloblang method and function, checked at parse time as Bento does.", ""]
for kind, key, call in (("METHODS", "bloblang-methods", "this.{}()"), ("FUNCTIONS", "bloblang-functions", "{}()")):
    rows = [(n, first_required(call.format(n))) for n in names[key]]
    out.append(f"pub(crate) const REQUIRED_{kind}: &[(&str, &str)] = &[")
    out += [f'    ("{n}", "{p}"),' for n, p in rows if p]
    out.append("];")
    out.append("")
with open(os.path.join(ROOT, "crates", "ekiben-bloblang", "src", "required_params.rs"), "w") as f:
    f.write("\n".join(out))
