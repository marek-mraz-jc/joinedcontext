TEMPLATE = Path(__file__).with_name("datacube.blobl")


def mapping(datacube: dict) -> str:
    """The Bloblang jc-core renders from a step's `datacube` parameters (datacube::bloblang), for the
    Bento decode tests and the temporal audit: the same placeholders, the cube table spaced as serde writes it."""
    table = {code: {k: c.get(k) for k in ("area", "indicator", "keys", "period", "source", "unit", "update")}
             for code, c in datacube["cubes"].items()}
    for c in table.values():
        c["keys"] = c["keys"] or []
    return (TEMPLATE.read_text()
            .replace("{whole_area}", json.dumps(datacube["wholeArea"]))
            .replace("{dataset_page}", json.dumps(datacube["datasetPage"].replace("{cube}", "%v")))
            .replace("{cubes}", json.dumps(table, ensure_ascii=False, sort_keys=True)))


def memory(cells: int) -> int:
    """The runner's memory for a topic, by its largest cube: about 2 kB per decoded cell."""
    # ponytail: a linear guess from the cell count; at CUBE_LIMIT it is 128 MB above the floor.
    return min(2048, max(128, -(-cells * 2 // 1024 // 64) * 64 + 128))


def source_names(d: dict, parts: dict[str, list[tuple[str, int]]]) -> list[str]:
    """The cube's DataSources: `susr-<code>` for a whole cube, `susr-<code>-<n>` per slice."""
    n = len(parts[d["code"]])
    return [f"susr-{d['code']}"] if n == 1 else [f"susr-{d['code']}-{i}" for i in range(1, n + 1)]


def chart(topic: dict) -> str:
    """The topic's declared chart: each indicator of one table for the whole country, summed per year.

    The catalogue holds no DataStore table to chart (T-5060), and these spaces keep no history
    (history off), so a topic that wants a chart declares it here (T-5089).
    """
    cube = topic.get("chart")
    if not cube:
        return ""
    spec = {
        "$schema": "https://vega.github.io/schema/vega-lite/v5.json",
        "data": {"name": "source"},
        "mark": {"type": "line", "point": True},
        "encoding": {
            "x": {"field": "refPeriod", "type": "ordinal", "title": None},
            "y": {"aggregate": "sum", "field": "kpiValue", "type": "quantitative", "title": None},
            "color": {"field": "name", "type": "nominal", "title": None},
            "tooltip": [{"field": "name", "type": "nominal"}, {"field": "refPeriod", "type": "ordinal"},
                        {"aggregate": "sum", "field": "kpiValue", "type": "quantitative", "format": ",d"}],
        },
    }
    data = {"source": "odata", "entitySet": TYPE, "$filter": f"dataSet eq '{cube}' and refArea eq 'SK0'",
            "$select": "refPeriod,kpiValue,name"}
    t = topic["title"]
    return f"""
    visualizations:
      - name: {cube}-rocne
        title: {{ sk: {q(t['sk'] + ' za SR podľa rokov')}, en: {q(t['en'] + ' in Slovakia by year')} }}
        description: {{ sk: {q(f'Súčet mesačných hodnôt tabuľky {cube} za celú SR v každom roku, jedna čiara na ukazovateľ.')}, en: {q(f'The monthly values of table {cube} for the whole of Slovakia summed per year, one line per indicator.')} }}
        data: {json.dumps(data, ensure_ascii=False)}
        spec: {json.dumps(spec, ensure_ascii=False)}"""


