AREA = ("Územie", "Obce", "Kraj", "Region", "SR + vybrané okresy", "Obce + Obce spolu")
INDICATOR = ("Ukazovateľ", "Ukazovatele", "Vybrané ukazovatele")
UNIT = ("Merná jednotka",)


def role(note: str | None) -> str:
    n = (note or "").strip()
    if n in PERIOD:
        return "period"
    if n.startswith("0 SR") or n in AREA:
        return "area"
    if n in INDICATOR:
        return "indicator"
    if n in UNIT:
        return "unit"
    return "key"


def roles(dimensions: dict) -> dict:
    """The cube's dimension per role: the first of each role, every other dimension a key, in order."""
    out = {"period": None, "area": None, "indicator": None, "unit": None, "keys": []}
    for name, d in dimensions.items():
        r = role(d.get("note"))
        if r != "key" and out[r] is None:
            out[r] = name
        else:
            out["keys"].append(name)
    return out


def code_of(item: dict) -> str | None:
    m = CODE.search(item.get("href", ""))
    return m.group(1) if m else None


def label(text: str | None) -> str | None:
    """The collection's label, or None for a missing one or the placeholder "Default"."""
    text = " ".join((text or "").split())
    return text if text and text != "Default" else None


def datasets(collection_sk: dict, collection_en: dict) -> list[dict]:
    """Every dataset of the collection: its code, labels (sk falls back to en, en to sk, both to
    the theme's name: the ps cubes have none), last update and dimensions in the order the
    dataset URL takes them."""
    en = {code_of(i): label(i.get("label")) for i in collection_en["link"]["item"]}
    out = []
    for item in collection_sk["link"]["item"]:
        code = code_of(item)
        if code is None:
            continue
        sk = label(item.get("label"))
        theme = THEMES.get(code[:2], ({"sk": code, "en": code},))[0]
        out.append({"code": code, "theme": code[:2], "update": item.get("update") or "",
                    "title": {"sk": sk or en.get(code) or theme["sk"], "en": en.get(code) or sk or theme["en"]},
                    "dimensions": item.get("dimension") or {}})
    return out


def selected(items: list[dict], topics: list[dict]) -> list[tuple[dict, list[dict]]]:
    """Each topic with the collection's datasets it names, in its order. A code the collection does
    not have, or one with no period dimension (nothing could date its cells), is an error that
    names it: a topic never ships short of a table."""
    by = {d["code"]: d for d in items}
    out = []
    for topic in topics:
        missing = [c for c in topic["cubes"] if c not in by or not roles(by[c]["dimensions"])["period"]]
        if missing:
            raise ValueError(f"{topic['name']}: DATAcube has no dated table {', '.join(missing)}")
        out.append((topic, [by[c] for c in topic["cubes"]]))
    return out


def fetch(url: str, cache: Path | None, waits=(5, 30)) -> dict:
    """GET `url` as JSON, from the cache when it holds it; a 5xx or a network error is retried."""
    path = cache / (hashlib.sha256(url.encode()).hexdigest() + ".json") if cache else None
    if path and path.exists():
        return json.loads(path.read_text())
    for attempt in range(len(waits) + 1):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers={"Accept": "application/json"}), timeout=60) as r:
                body = r.read()
            break
        except urllib.error.HTTPError as e:
            if e.code < 500 or attempt == len(waits):
                raise
        except (urllib.error.URLError, TimeoutError, ConnectionError):
            if attempt == len(waits):
                raise
        time.sleep(waits[attempt])
    data = json.loads(body)
    if path:
        path.write_bytes(body)
    return data


def categories(ds: list[dict], get) -> dict[str, dict[str, list[str]]]:
    """code -> each dimension's category codes in their index order, dimensions in the collection's."""
    jobs = {(d["code"], name): f"{API}/dimension/{d['code']}/{name}?lang=sk&type=json"
            for d in ds for name in d["dimensions"]}
    with concurrent.futures.ThreadPoolExecutor(4) as pool:
        found = dict(zip(jobs, pool.map(lambda u: get(u).get("category", {}).get("index") or {}, jobs.values())))
    out: dict[str, dict[str, list[str]]] = {}
    for (code, name), index in found.items():
        out.setdefault(code, {})[name] = sorted(index, key=index.get) if isinstance(index, dict) else list(index)
    return out


def sizes(ds: list[dict], get) -> dict[str, int]:
    """code -> the cube's cell count, the product of its dimensions' category counts."""
    return {code: math.prod(len(c) for c in dims.values()) for code, dims in categories(ds, get).items()}


def dataset_url(d: dict, only: dict[str, list[str]] | None = None) -> str:
    """The cube: `all` for every dimension the collection lists, in its order, or the categories
    `only` names for a dimension, comma-separated."""
    only = only or {}
    return f"{API}/dataset/{d['code']}/" + "/".join(
        ",".join(urllib.parse.quote(c, safe="") for c in only[n]) if n in only else "all"
        for n in d["dimensions"]) + "?lang=sk&type=json"


def slices(d: dict, dims: dict[str, list[str]]) -> list[tuple[str, int]] | None:
    """The requests that read the cube: (address, cells). The whole cube when it is at most
    CUBE_LIMIT cells; else as few slices of one dimension as keep each request under it, the
    categories split evenly, every one in one slice. None when no dimension can.

    Decided (worker-3, owner may override; T-4433): never a period dimension. DATAcube's period codes
    carry their status (`2026 (p)` turns `2026 (d)`) and a new period is a new code, so a slice of
    periods would stop answering or miss the newest; an indicator or a country stays.
    The dimension needing the fewest slices wins, then the one with the fewest categories."""
    total = math.prod(len(c) for c in dims.values())
    if total <= CUBE_LIMIT:
        return [(dataset_url(d), total)]
    best = None
    for name, codes in dims.items():
        if role(d["dimensions"].get(name, {}).get("note")) == "period" or not codes:
            continue
        rest = total // len(codes)
        per = CUBE_LIMIT // rest
        if per < 1:
            continue
        n = -(-len(codes) // per)
        if best is None or (n, len(codes)) < best[:2]:
            best = (n, len(codes), name)
    if best is None:
        return None
    n, k, name = best
    size = -(-k // n)
    return [(dataset_url(d, {name: dims[name][i:i + size]}), total // k * len(dims[name][i:i + size]))
            for i in range(0, k, size)]


